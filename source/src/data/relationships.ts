export function relationsOf(e) {
  let t = [];
  for (let n of RELATIONSHIPS) {
    if (n.from === e) {
      t.push({
        type: n.type,
        label: RELATION_LABELS[n.type].forward,
        otherId: n.to,
        note: n.note,
        direction: 'forward',
      });
    } else if (n.to === e) {
      t.push({
        type: n.type,
        label: RELATION_LABELS[n.type].inverse,
        otherId: n.from,
        note: n.note,
        direction: 'inverse',
      });
    }
  }
  return t;
}
